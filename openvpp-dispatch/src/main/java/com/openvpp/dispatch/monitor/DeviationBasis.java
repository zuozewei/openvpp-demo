package com.openvpp.dispatch.monitor;

/**
 * 偏差判定基准 —— 方向性超差的计算口径（第 55 篇"零目标用绝对偏差"验收格）。
 *
 * 零目标功率（停机/回原状）时比例偏差 |实测 − 目标| / 目标 无定义（除零），
 * 会把"零目标但有实际功率"的异常掩盖掉 —— 因此零目标一律改用绝对偏差
 * |实测 − 0| 与容差直接比较，不论事件方向。
 */
public enum DeviationBasis {

    /** 方向性偏差：按事件方向判单侧超差 —— 削峰看实际是否高于目标（压不下来），
     *  填谷看实际是否低于目标（抬不上去）；另一侧属过度响应/压过头，归效果评估篇 */
    DIRECTIONAL,

    /** 绝对偏差（零目标专用）：|实测 − 0| 与容差比较，两个方向通用 */
    ABSOLUTE_ZERO_TARGET
}
