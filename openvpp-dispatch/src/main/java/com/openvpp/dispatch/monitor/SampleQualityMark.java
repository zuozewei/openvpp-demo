package com.openvpp.dispatch.monitor;

/**
 * 样点质量标记 —— 监测方对入库样点的独立判定（第 55 篇"监测与质量"验收格）。
 *
 * 与 iot 侧 {@code TelemetryAnomaly}（注入方自证）刻意分开：注入标记是设备/通道
 * 的"自述"，监测判定必须独立做出——重复按（序号, 采样时标）去重，迟到按
 * （接收时标 − 采样时标）与阈值比较，乱序按采样时标单调性校验（第 55 篇
 * "不能设备说正常就正常"）。
 *
 * 正常样点标记集合为空；缺失与失联无样点载体，不打标（缺失表现为序号缺口，
 * 由 {@link SampleGap} 记录）。
 */
public enum SampleQualityMark {

    /** 重复样点：同（场站, 资源, 序号, 采样时标）已入库过 —— 不充当达标证据 */
    DUPLICATE,

    /** 迟到样点：接收时标 − 采样时标超过迟到阈值 —— 采样时刻已过，不充当本指令达标证明 */
    LATE,

    /** 乱序样点：采样时标早于本流已见最大采样时标（重复副本除外）—— 曲线按采样时标重排后仍可用 */
    OUT_OF_ORDER
}
