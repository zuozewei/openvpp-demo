package com.openvpp.iot.simulate;

/**
 * 注入异常标记 —— 故障注入产出的样点显式携带的异常种类。
 *
 * 只有 {@link FaultInjectionProfile} 启用的注入才会打标，正常样点标记集合为空。
 * 打标目的是让验收方能直接断言"注入确实生效"（第 55 篇故障注入验收）；
 * 平台侧的质量判定仍须独立识别异常（按序号去重、按双时标判迟到、按采样时标判乱序），
 * 不能设备说正常就正常——标记是注入方的自证，不是监测方的结论。
 *
 * 缺失与失联无样点载体，不打标：缺失表现为流中序号缺口，失联表现为断流 + 下行无回执。
 */
public enum TelemetryAnomaly {

    /** 重复样点：与某前序样点同资源、同序号、同采样时标再次发出 */
    DUPLICATE,

    /** 迟到样点：接收时标显著晚于采样时标（迟到时延由注入档案指定） */
    LATE,

    /** 乱序样点：在发出流中先于采样时标更早的样点到达 */
    OUT_OF_ORDER,

    /** 方向性偏差：数值被注入恒定偏移（如系统性偏低），用于削峰/填谷方向性告警验收 */
    DIRECTIONAL_BIAS
}
