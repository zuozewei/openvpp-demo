package com.openvpp.iot.simulate;

/**
 * 遥测数据来源 —— 样点级来源标记，把"这个数是怎么来的"写死在数据上。
 * 参考实现的缺口正是只区分了"是不是模拟生成"，监测侧无法回答"这条曲线能不能当证据"；
 * 本工程把来源分成三态，样点产出即带标记，杜绝用模拟值冒充实测充数：
 *
 *   SIMULATED 模拟值 —— 模拟设备通道产出（本包），仅供链路验证与演示，
 *                       不作效果结算/考核证据；
 *   MEASURED  测量值 —— 真实设备经接入链路上报（gateway remote 接入模式），
 *                       才具备充当响应效果证据的资格；
 *   ESTIMATED 推算值 —— 平台按模型推算（基线、预测等），既非实测也不假装实测。
 *
 * 监测与评估按来源取数：模拟值可演示流程，测量值才可作证据（第 55 篇
 * "模拟与测量来源可辨"验收格的落点；推算值属第 56 篇基线口径，单列）。
 */
public enum TelemetryDataSource {

    /** 模拟值：模拟设备通道产出 */
    SIMULATED,

    /** 测量值：真实设备接入链路上报（remote 模式） */
    MEASURED,

    /** 推算值：平台模型推算（基线/预测），非实测 */
    ESTIMATED
}
